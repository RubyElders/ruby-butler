#[test]
fn global_project_input_preserves_settings_and_rejects_conflicts_without_writing() {
    let fixture = Fixture::new();
    fs::write(fixture.project().join("Gemfile"), "gem 'rake', '>= 13'").unwrap();
    let destination = fixture.root.path().join("custom.toml");
    fs::write(
        &destination,
        include_str!("fixtures/export_gemfile_tests/global_project_input_preserves_settings_and_rejects_conflicts_without_writing-1.toml"),
    )
    .unwrap();
    let before = fs::read_to_string(&destination).unwrap();
    let output = fixture.run(&["-P", "custom.toml", "export-gemfile", "tea-room/Gemfile"]);
    success(&output);
    let parsed = stdout(&output);
    assert_eq!(fs::read_to_string(&destination).unwrap(), before);
    assert_eq!(parsed["project"]["name"].as_str(), Some("kept"));
    assert_eq!(parsed["scripts"]["test"].as_str(), Some("rspec"));
    let original = "[dependencies]\nrake='< 12'\n";
    fs::write(&destination, original).unwrap();
    let output = fixture.run(&["export-gemfile", "tea-room/Gemfile", "-P", "custom.toml"]);
    assert!(!output.status.success());
    assert!(
        String::from_utf8_lossy(&output.stderr).contains("Conflicting dependency rake.version")
    );
    assert_eq!(fs::read_to_string(&destination).unwrap(), original);
}

#[test]
fn failures_do_not_overwrite_destination_or_input() {
    let fixture = Fixture::new();
    let gemfile = fixture.project().join("Gemfile");
    fs::write(&gemfile, "gem 'rake'").unwrap();
    let output = fixture.run(&[
        "export-gemfile",
        "tea-room/Gemfile",
        "-o",
        "tea-room/Gemfile",
    ]);
    assert!(!output.status.success());
    assert_eq!(fs::read_to_string(&gemfile).unwrap(), "gem 'rake'");
    let project = fixture.project().join("rbproject.toml");
    fs::write(&project, "[project]\nname='kept'").unwrap();
    fs::write(&gemfile, "raise 'deliberate failure'").unwrap();
    let output = fixture.run(&["export-gemfile", "tea-room/Gemfile"]);
    assert!(!output.status.success());
    assert!(String::from_utf8_lossy(&output.stderr).contains("deliberate failure"));
    assert_eq!(
        fs::read_to_string(project).unwrap(),
        "[project]\nname='kept'"
    );
    let output = fixture
        .command()
        .env("BUNDLE_GEMFILE", "missing")
        .arg("export-gemfile")
        .output()
        .unwrap();
    assert!(!output.status.success());
    assert!(String::from_utf8_lossy(&output.stderr).contains("Gemfile not found"));
}

