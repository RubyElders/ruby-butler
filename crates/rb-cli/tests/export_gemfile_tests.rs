#[test]
fn optional_kdl_output_uses_the_same_global_project_settings() {
    let fixture = Fixture::new();
    fs::write(fixture.project().join("Gemfile"), "gem 'rails', '~> 8.0'; source 'https://gems.example.com' do\n gem 'internal', '~> 2.0', require: false\nend").unwrap();
    fs::write(
        fixture.project().join("settings.toml"),
        "[project]\nname='shared settings'\n",
    )
    .unwrap();
    for output_file in [None, Some("result.kdl")] {
        let mut command = fixture.command();
        command
            .env("RB_WORK_DIR", "tea-room")
            .env("RB_PROJECT", "settings.toml")
            .args(["export-gemfile", "--format", "kdl"]);
        if let Some(path) = output_file {
            command.args(["--output", path]);
        }
        let output = command.output().unwrap();
        success(&output);
        let text = if let Some(path) = output_file {
            assert!(output.stdout.is_empty());
            fs::read_to_string(fixture.project().join(path)).unwrap()
        } else {
            String::from_utf8(output.stdout).unwrap()
        };
        let document: kdl::KdlDocument = text.parse().unwrap();
        assert_eq!(
            document
                .get("project")
                .unwrap()
                .children()
                .unwrap()
                .get("name")
                .unwrap()
                .get(0)
                .unwrap()
                .as_string(),
            Some("shared settings")
        );
        let source = document
            .nodes()
            .iter()
            .find(|node| node.name().value() == "source")
            .unwrap();
        assert_eq!(
            source.get(0).unwrap().as_string(),
            Some("https://gems.example.com")
        );
        let gem = source
            .children()
            .unwrap()
            .nodes()
            .iter()
            .find(|node| node.get(0).and_then(kdl::KdlValue::as_string) == Some("internal"))
            .unwrap();
        assert_eq!(gem.get("require").unwrap().as_bool(), Some(false));
    }
    assert!(!fixture.project().join("rbproject.toml").exists());
    let output = fixture.run(&["export-gemfile", "--format", "yaml"]);
    assert!(!output.status.success());
    assert!(output.stdout.is_empty());
}

