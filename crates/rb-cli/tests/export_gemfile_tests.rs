#![cfg(unix)]

use std::{
    fs,
    os::unix::fs::PermissionsExt,
    path::Path,
    process::{Command, Output},
};

struct Fixture {
    root: tempfile::TempDir,
}

impl Fixture {
    fn new() -> Self {
        let root = tempfile::tempdir().unwrap();
        let bin = root.path().join("rubies/ruby-9.9.9/bin");
        fs::create_dir_all(&bin).unwrap();
        let ruby =
            which::which(std::env::var_os("RB_GEMFILE_RUBY").unwrap_or_else(|| "ruby".into()))
                .unwrap();
        let quoted = ruby.to_str().unwrap().replace('\'', "'\\''");
        fs::write(
            bin.join("ruby"),
            format!("#!/bin/sh\nexec '{quoted}' \"$@\"\n"),
        )
        .unwrap();
        fs::set_permissions(bin.join("ruby"), fs::Permissions::from_mode(0o755)).unwrap();
        fs::write(root.path().join("config.toml"), "").unwrap();
        fs::create_dir(root.path().join("tea-room")).unwrap();
        Self { root }
    }

    fn project(&self) -> std::path::PathBuf {
        self.root.path().join("tea-room")
    }

    fn command(&self) -> Command {
        let mut command = Command::new(env!("CARGO_BIN_EXE_rb"));
        command
            .current_dir(self.root.path())
            .args(["-c", "config.toml", "-r", "9.9.9"])
            .env("RB_RUBIES_DIR", self.root.path().join("rubies"))
            .env_remove("BUNDLE_GEMFILE")
            .env_remove("RB_PROJECT")
            .env_remove("RB_WORK_DIR")
            .env_remove("RB_NO_BUNDLER")
            .env_remove("RB_LOG_LEVEL")
            .env_remove("RB_VERBOSE")
            .env_remove("RB_VERY_VERBOSE");
        command
    }

    fn run(&self, args: &[&str]) -> Output {
        self.command().args(args).output().unwrap()
    }
}

fn success(output: &Output) {
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

fn stdout(output: &Output) -> toml::Value {
    normalize_export(toml::from_str(std::str::from_utf8(&output.stdout).unwrap()).unwrap())
}

fn read(path: impl AsRef<Path>) -> toml::Value {
    normalize_export(toml::from_str(&fs::read_to_string(path).unwrap()).unwrap())
}

fn normalize_export(mut value: toml::Value) -> toml::Value {
    let mut model = value.as_table().unwrap().clone();
    model.retain(|key, _| {
        matches!(
            key,
            "bundle" | "dependencies" | "sources" | "groups" | "gemspecs"
        )
    });
    let manifest: rb_gemfile::Manifest = toml::Value::Table(model).try_into().unwrap();
    let mut dependencies = toml::Table::new();
    for (name, dependency) in &manifest.dependencies {
        let default = rb_gemfile::Dependency {
            version: dependency.version.clone(),
            ..Default::default()
        };
        let entry = if dependency == &default && dependency.version.len() == 1 {
            toml::Value::String(dependency.version[0].clone())
        } else {
            toml::Value::try_from(dependency).unwrap()
        };
        dependencies.insert(name.clone(), entry);
    }
    for (_, dependency) in &mut dependencies {
        if let Some(table) = dependency.as_table_mut() {
            table.remove("enabled");
        }
    }
    value
        .as_table_mut()
        .unwrap()
        .insert("dependencies".into(), toml::Value::Table(dependencies));
    let bundle = value
        .as_table_mut()
        .unwrap()
        .entry("bundle")
        .or_insert_with(|| toml::Value::Table(toml::Table::new()));
    if let Some(source) = manifest.bundle.source {
        bundle
            .as_table_mut()
            .unwrap()
            .insert("source".into(), toml::Value::String(source));
    }
    value
}

#[test]
fn exports_with_work_dir_and_initializes_missing_project_settings() {
    let fixture = Fixture::new();
    fs::write(
        fixture.project().join("Gemfile"),
        "raise 'Bundler was loaded' if Gem.loaded_specs.key?('bundler'); source 'https://rubygems.org'; gem 'rake', require: false",
    )
    .unwrap();
    let output = fixture.run(&["export-gemfile", "-C", "tea-room", "-R", "../rubies"]);
    success(&output);
    let project = stdout(&output);
    assert_eq!(project["project"]["name"].as_str(), Some("tea-room"));
    assert_eq!(
        project["dependencies"]["rake"]["require"].as_bool(),
        Some(false)
    );
    assert!(
        !std::str::from_utf8(&output.stdout)
            .unwrap()
            .contains("enabled")
    );
    let raw: toml::Value = toml::from_str(std::str::from_utf8(&output.stdout).unwrap()).unwrap();
    assert!(raw.get("sources").is_some());
    assert!(
        String::from_utf8_lossy(&output.stdout)
            .starts_with("# Generated by Ruby Butler. Do not edit.\n")
    );
    assert!(!fixture.project().join("rbproject.toml").exists());
    assert!(!fixture.project().join("Gemfile.lock").exists());
}

