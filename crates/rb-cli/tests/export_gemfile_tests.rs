#[test]
fn reexport_replaces_generated_declarations_and_preserves_project_settings() {
    let fixture = Fixture::new();
    let gemfile = fixture.project().join("Gemfile");
    fs::write(
        &gemfile,
        "source 'https://rubygems.org'; gem 'rake', '>= 13'; gem 'removed'",
    )
    .unwrap();
    let project = fixture.project().join("rbproject.toml");
    fs::write(
        &project,
        include_str!("fixtures/export_gemfile_tests/reexport_replaces_generated_declarations_and_preserves_project_settings-1.toml"),
    )
    .unwrap();
    success(&fixture.run(&[
        "export-gemfile",
        "tea-room/Gemfile",
        "-o",
        "tea-room/rbproject.toml",
    ]));
    fs::write(&gemfile, "source 'https://other.test'; gem 'rake', '>= 14'; install_if -> { ENV['WITH_DEBUG'] == '1' } do\n gem 'debug'\nend").unwrap();
    for enabled in ["1", "0"] {
        let output = fixture
            .command()
            .env("WITH_DEBUG", enabled)
            .args([
                "export-gemfile",
                "tea-room/Gemfile",
                "-o",
                "tea-room/rbproject.toml",
            ])
            .output()
            .unwrap();
        success(&output);
        assert!(output.stdout.is_empty());
        let parsed = read(&project);
        assert_eq!(parsed["project"]["name"].as_str(), Some("kept"));
        assert_eq!(parsed["scripts"]["test"].as_str(), Some("rspec"));
        assert_eq!(
            parsed["bundle"]["source"].as_str(),
            Some("https://other.test")
        );
        assert_eq!(parsed["dependencies"]["rake"].as_str(), Some(">= 14"));
        assert!(parsed["dependencies"].get("removed").is_none());
        assert_eq!(
            parsed["dependencies"].get("debug").is_some(),
            enabled == "1"
        );
    }
}

#[test]
fn global_project_input_and_output_are_independent() {
    let fixture = Fixture::new();
    fs::write(fixture.project().join("Gemfile"), "gem 'rake'").unwrap();
    let input = fixture.project().join("from-env.toml");
    let original = "[project]\nname='from environment'\n";
    fs::write(&input, original).unwrap();
    let output = fixture
        .command()
        .env("RB_WORK_DIR", "tea-room")
        .env("RB_PROJECT", "from-env.toml")
        .args(["export-gemfile", "--output", "chosen.toml"])
        .output()
        .unwrap();
    success(&output);
    assert!(output.stdout.is_empty());
    assert!(String::from_utf8_lossy(&output.stderr).contains("Exported"));
    assert_eq!(
        read(fixture.project().join("chosen.toml"))["project"]["name"].as_str(),
        Some("from environment")
    );
    assert_eq!(fs::read_to_string(&input).unwrap(), original);
    assert!(!fixture.project().join("rbproject.toml").exists());
    let output = fixture
        .command()
        .env("RB_WORK_DIR", "tea-room")
        .env("RB_PROJECT", "from-env.toml")
        .arg("export-gemfile")
        .output()
        .unwrap();
    success(&output);
    assert_eq!(
        stdout(&output)["project"]["name"].as_str(),
        Some("from environment")
    );
    assert_eq!(fs::read_to_string(input).unwrap(), original);
}

